# Variables ********************************************************************

# Marks a folder as trlcdoc output. trlcdoc only deletes folders containing it.
MARKER_FILE = ".trlcdoc"
MARKER_TEXT = "Generated by trlcdoc. The whole folder is removed by 'trlcdoc clean' !\n"

LOG = logging.getLogger(__name__)

# Classes **********************************************************************


class TrlcdocError(Exception):
    """Error that stops the documentation build with a message."""


# Functions ********************************************************************


def find_tool(name: str, hint: str = "Install the trlcdoc package dependencies.") -> str:
    # lobster-trace: SwRequirements.sw_req_trlc_conversion
    # lobster-trace: SwRequirements.sw_req_test_run
    # lobster-trace: SwRequirements.sw_req_trace_report
    # lobster-trace: SwRequirements.sw_req_external_tools
    """Find a console script, preferring the one of the running Python environment.

    Tools that are not installed with trlcdoc, e.g. Java, are searched on the PATH.

    Args:
        name (str): Name of the console script, e.g. 'lobster-trlc'.
        hint (str): How to install the tool, added to the error message.

    Returns:
        str: Path of the executable.

    Raises:
        TrlcdocError: If the tool is not installed.
    """
    script_dir = Path(sys.executable).parent
    candidates = [script_dir / name, script_dir / f"{name}.exe"]
    tool = next((str(path) for path in candidates if path.is_file()), shutil.which(name))
    if tool is None:
        raise TrlcdocError(f"Tool '{name}' not found. {hint}")
    return tool


def find_graphviz(purpose: str) -> str:
    # lobster-trace: SwRequirements.sw_req_external_tools
    """Find the Graphviz dot program, so a missing Graphviz stops the build instead of leaving out diagrams.

    Args:
        purpose (str): What needs Graphviz, added to the error message, e.g. 'for the tracing policy diagram'.

    Returns:
        str: Path of the dot executable.

    Raises:
        TrlcdocError: If dot is not on the PATH.
    """
    return find_tool("dot", f"Graphviz is needed {purpose}, see https://graphviz.org.")


def run(cmd: list[str], cwd: Path, env: dict[str, str] | None = None, stdin: str | None = None) -> int:
    # lobster-trace: SwRequirements.sw_req_exit_code
    """Run an external command and stop the build if it fails.

    Args:
        cmd (list[str]): Command and its arguments.
        cwd (Path): Working directory.
        env (dict[str, str] | None): Additional environment variables.
        stdin (str | None): Text passed to the standard input of the command.

    Returns:
        int: The exit code, which is always 0.

    Raises:
        TrlcdocError: If the command returns a non-zero exit code.
    """
    returncode = run_unchecked(cmd, cwd, env, stdin)
    if returncode != 0:
        raise TrlcdocError(f"Command failed with exit code {returncode}: {command_line(cmd)}")
    return returncode


def run_unchecked(cmd: list[str], cwd: Path, env: dict[str, str] | None = None, stdin: str | None = None) -> int:
    # lobster-trace: SwRequirements.sw_req_test_run
    # lobster-trace: SwRequirements.sw_req_verbose_output
    """Run an external command and return its exit code.

    The command is always shown. Verbose output adds the working folder, the environment
    variables the command gets from trlcdoc, the size of its input, its exit code and duration.
    The output of the command is not captured, it goes directly to the console.

    Args:
        cmd (list[str]): Command and its arguments.
        cwd (Path): Working directory.
        env (dict[str, str] | None): Additional environment variables.
        stdin (str | None): Text passed to the standard input of the command.

    Returns:
        int: The exit code of the command.
    """
    full_env = dict(os.environ)
    full_env.update(env or {})
    LOG.info("  $ %s", command_line(cmd))
    LOG.debug("cwd: %s", cwd)
    for name, value in sorted(redact_env(env or {}).items()):
        LOG.debug("env: %s=%s", name, value)
    if stdin is not None:
        LOG.debug("stdin: %d characters", len(stdin))
    if LOG.isEnabledFor(TRACE):
        for name, value in sorted(redact_env(full_env).items()):
            LOG.log(TRACE, "environment: %s=%s", name, value)

    # Python buffers its output, the command writes directly to the console: keep the order.
    sys.stdout.flush()
    sys.stderr.flush()
    started = time.monotonic()
    returncode = subprocess.run(cmd, cwd=cwd, env=full_env, input=stdin, text=stdin is not None, check=False).returncode
    LOG.debug("exit code %d%s after %.1f s", returncode, _signal_name(returncode), time.monotonic() - started)
    return returncode


def _signal_name(returncode: int) -> str:
    # lobster-trace: SwRequirements.sw_req_verbose_output
    """Name the signal that ended a command.

    Args:
        returncode (int): Exit code of the command, negative for a signal on POSIX systems.

    Returns:
        str: The signal name in parentheses, e.g. ' (SIGKILL)', empty if no signal ended the command.
    """
    if returncode >= 0:
        return ""
    try:
        return f" ({signal.Signals(-returncode).name})"
    except ValueError:
        return ""


def _check_owned(output: Path) -> Path:
    # lobster-trace: SwRequirements.sw_req_delete_protection
    """Ensure the output folder was created by trlcdoc, before anything in it is deleted.

    A missing or empty folder is accepted. Any other folder must contain the marker file.

    Args:
        output (Path): The output folder.

    Returns:
        Path: The output folder.

    Raises:
        TrlcdocError: If the folder exists with content but without the marker file.
    """
    if output.exists():
        owned = output.is_dir() and ((output / MARKER_FILE).is_file() or not any(output.iterdir()))
        if not owned:
            raise TrlcdocError(
                f"{output} is not a trlcdoc output folder (no {MARKER_FILE} marker file), refusing to "
                "delete it. Check paths.output or remove the folder manually."
            )
    return output


def prepare_output(output: Path) -> Path:
    # lobster-trace: SwRequirements.sw_req_output_folder
    # lobster-trace: SwRequirements.sw_req_delete_protection
    """Create the output folder if needed and mark it as owned by trlcdoc.

    Args:
        output (Path): The output folder.

    Returns:
        Path: The output folder.

    Raises:
        TrlcdocError: If the folder exists with content but without the marker file.
    """
    _check_owned(output).mkdir(parents=True, exist_ok=True)
    (output / MARKER_FILE).write_text(MARKER_TEXT, encoding="utf-8")
    return output


def clean_dir(folder: Path, output: Path) -> Path:
    # lobster-trace: SwRequirements.sw_req_output_folder
    # lobster-trace: SwRequirements.sw_req_delete_protection
    """Create an empty folder inside the output folder, removing previous content.

    Args:
        folder (Path): The folder, a subfolder of the output folder.
        output (Path): The output folder.

    Returns:
        Path: The folder.

    Raises:
        TrlcdocError: If the folder is not inside a trlcdoc output folder.
    """
    if folder == output or not folder.is_relative_to(output):
        raise TrlcdocError(f"{folder} is not inside the output folder {output}, refusing to delete it.")
    prepare_output(output)
    if folder.exists():
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    return folder


def remove_output(output: Path) -> bool:
    # lobster-trace: SwRequirements.sw_req_clean
    # lobster-trace: SwRequirements.sw_req_delete_protection
    """Remove the output folder with all its content.

    Args:
        output (Path): The output folder.

    Returns:
        bool: True if the folder existed and was removed.

    Raises:
        TrlcdocError: If the folder exists with content but without the marker file.
    """
    existed = _check_owned(output).exists()
    if existed:
        shutil.rmtree(output)
    return existed


def git_output(args: list[str], cwd: Path) -> str | None:
    # lobster-trace: SwRequirements.sw_req_trace_report
    """Run a git command and return its output.

    Args:
        args (list[str]): git arguments.
        cwd (Path): Working directory.

    Returns:
        str | None: The stripped output, or None if git failed.
    """
    result = None
    LOG.debug("git %s in %s", " ".join(args), cwd)
    try:
        proc = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=False)
        if proc.returncode == 0:
            result = proc.stdout.strip()
    except OSError:
        result = None
    return result


def git_root(path: Path) -> Path | None:
    # lobster-trace: SwRequirements.sw_req_trace_report
    # lobster-trace: SwRequirements.sw_req_markdown_links
    """Get the root folder of the git repository that contains a folder.

    The project root is a subfolder of the repository if several projects share one repository.

    Args:
        path (Path): A folder inside the repository, e.g. the project root.

    Returns:
        Path | None: The resolved repository root, or None if the folder is not in a git repository.
    """
    toplevel = git_output(["rev-parse", "--show-toplevel"], path)
    return Path(toplevel).resolve() if toplevel else None


def repository_url(repository: str, root: Path) -> str:
    # lobster-trace: SwRequirements.sw_req_trace_report
    # lobster-trace: SwRequirements.sw_req_markdown_links
    """Get the repository URL for links to project files.

    Args:
        repository (str): Configured repository URL or 'auto' for the origin remote.
        root (Path): Project root, the git working directory.

    Returns:
        str: HTTPS repository URL without '.git' suffix, the base of the file links.

    Raises:
        TrlcdocError: If 'auto' is configured and git has no origin remote.
    """
    url = repository
    if url == "auto":
        url = git_output(["remote", "get-url", "origin"], root)
        if url is None:
            raise TrlcdocError("project.repository is 'auto', but 'git remote get-url origin' failed.")
        # git@github.com:owner/repo.git -> https://github.com/owner/repo.git
        url = re.sub(r"^git@([^:]+):", r"https://\1/", url)
    # https://github.com/owner/repo.git -> https://github.com/owner/repo
    return re.sub(r"\.git$", "", url)


