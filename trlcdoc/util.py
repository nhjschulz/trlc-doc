# Imports **********************************************************************

import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional

# Variables ********************************************************************

# Marks a folder as trlcdoc output. trlcdoc only deletes folders containing it.
MARKER_FILE = ".trlcdoc"
MARKER_TEXT = "Generated by trlcdoc. The whole folder is removed by 'trlcdoc clean' !\n"

# Classes **********************************************************************


class TrlcdocError(Exception):
    """Error that stops the documentation build with a message."""

# Functions ********************************************************************


def find_tool(name: str) -> str:
    """Find a console script, preferring the one of the running Python environment.

    Args:
        name (str): Name of the console script, e.g. 'lobster-trlc'.

    Returns:
        str: Path of the executable.

    Raises:
        TrlcdocError: If the tool is not installed.
    """
    script_dir = Path(sys.executable).parent
    candidates = [script_dir / name, script_dir / f"{name}.exe"]
    tool = next((str(path) for path in candidates if path.is_file()), shutil.which(name))
    if tool is None:
        raise TrlcdocError(f"Tool '{name}' not found. Install the trlcdoc package dependencies.")
    return tool


def run(cmd: List[str], cwd: Path, env: Optional[Dict[str, str]] = None) -> int:
    """Run an external command and stop the build if it fails.

    Args:
        cmd (List[str]): Command and its arguments.
        cwd (Path): Working directory.
        env (Optional[Dict[str, str]]): Additional environment variables.

    Returns:
        int: The exit code, which is always 0.

    Raises:
        TrlcdocError: If the command returns a non-zero exit code.
    """
    returncode = run_unchecked(cmd, cwd, env)
    if returncode != 0:
        raise TrlcdocError(f"Command failed with exit code {returncode}: {' '.join(cmd)}")
    return returncode


def run_unchecked(cmd: List[str], cwd: Path, env: Optional[Dict[str, str]] = None) -> int:
    """Run an external command and return its exit code.

    Args:
        cmd (List[str]): Command and its arguments.
        cwd (Path): Working directory.
        env (Optional[Dict[str, str]]): Additional environment variables.

    Returns:
        int: The exit code of the command.
    """
    full_env = dict(os.environ)
    full_env.update(env or {})
    print(f"  $ {' '.join(cmd)}", flush=True)
    return subprocess.run(cmd, cwd=cwd, env=full_env, check=False).returncode


def _check_owned(output: Path) -> Path:
    """Ensure the output folder was created by trlcdoc, before anything in it is deleted.

    A missing or empty folder is accepted. Any other folder must contain the marker file.

    Args:
        output (Path): The output folder.

    Returns:
        Path: The output folder.

    Raises:
        TrlcdocError: If the folder exists with content but without the marker file.
    """
    if output.exists():
        owned = output.is_dir() and ((output / MARKER_FILE).is_file() or not any(output.iterdir()))
        if not owned:
            raise TrlcdocError(
                f"{output} is not a trlcdoc output folder (no {MARKER_FILE} marker file), refusing to "
                "delete it. Check paths.output or remove the folder manually.")
    return output


def prepare_output(output: Path) -> Path:
    """Create the output folder if needed and mark it as owned by trlcdoc.

    Args:
        output (Path): The output folder.

    Returns:
        Path: The output folder.

    Raises:
        TrlcdocError: If the folder exists with content but without the marker file.
    """
    _check_owned(output).mkdir(parents=True, exist_ok=True)
    (output / MARKER_FILE).write_text(MARKER_TEXT, encoding="utf-8")
    return output


def clean_dir(folder: Path, output: Path) -> Path:
    """Create an empty folder inside the output folder, removing previous content.

    Args:
        folder (Path): The folder, a subfolder of the output folder.
        output (Path): The output folder.

    Returns:
        Path: The folder.

    Raises:
        TrlcdocError: If the folder is not inside a trlcdoc output folder.
    """
    if folder == output or not folder.is_relative_to(output):
        raise TrlcdocError(f"{folder} is not inside the output folder {output}, refusing to delete it.")
    prepare_output(output)
    if folder.exists():
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    return folder


def remove_output(output: Path) -> bool:
    """Remove the output folder with all its content.

    Args:
        output (Path): The output folder.

    Returns:
        bool: True if the folder existed and was removed.

    Raises:
        TrlcdocError: If the folder exists with content but without the marker file.
    """
    existed = _check_owned(output).exists()
    if existed:
        shutil.rmtree(output)
    return existed


def git_output(args: List[str], cwd: Path) -> Optional[str]:
    """Run a git command and return its output.

    Args:
        args (List[str]): git arguments.
        cwd (Path): Working directory.

    Returns:
        Optional[str]: The stripped output, or None if git failed.
    """
    result = None
    try:
        proc = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=False)
        if proc.returncode == 0:
            result = proc.stdout.strip()
    except OSError:
        result = None
    return result

