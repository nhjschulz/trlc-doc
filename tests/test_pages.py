def _config(root: Path, index: str, report: str = "rst") -> Dict[str, Any]:
    """Write a start page and get the example configuration using it.

    Args:
        root (Path): Project root.
        index (str): Content of the start page.
        report (str): Format of the tracing report.

    Returns:
        Dict[str, Any]: The configuration data.
    """
    (root / "docs").mkdir(exist_ok=True)
    (root / "docs" / "index.rst").write_text(index, encoding="utf-8")
    data = base_config()
    data["trace"]["report"] = report
    data["html"] = {"index": "docs/index.rst"}
    return data


def test_toctree_check(project: Path, capsys: pytest.CaptureFixture) -> None:
    """The check step compares the toctrees of the project start page with the page names of the documents.

    Args:
        project (Path): Configuration file of the example project.
        capsys (pytest.CaptureFixture): pytest output capture.
    """
    root = project.parent

    # Wrong entries and missing documents are findings with a hint, exit code 1.
    config_file = write_config(root, _config(root, WRONG_INDEX))
    assert cli.main(["-c", str(config_file), "check"]) == 1
    out = capsys.readouterr().out
    assert ("html.index: toctree entry 'sw_architecture' is no page. Document 'sw_architecture' is the page "
            "'sw_architecture/index' (type trlc). Write {page:sw_architecture} to use its page name.") in out
    assert ("html.index: toctree entry 'sw_tracing_report' is no page. Document 'sw_tracing_report' is the page "
            "'sw_tracing_report/index' (type trace_report, trace.report: rst).") in out
    assert "html.index: toctree entry 'sw_tests_old' is no page of a document." in out
    # A document listed by a wrong entry is only reported once, with the fix.
    assert "document 'sw_architecture' (page 'sw_architecture/index') is not in any toctree" not in out
    assert "document 'sw_tracing_report'" not in out
    assert "html.index: document 'sw_test' (page 'sw_test/index') is not in any toctree. Add {page:sw_test}" in out
    assert "html.index: document 'sw_test_results' (page 'sw_test_results/index') is not in any toctree." in out
    # Pages of Sphinx extensions cannot be checked and are accepted.
    assert "api/example/index" not in out
    assert "finished with findings in: check" in out

    # The same start page is right for the tracing report in HTML format.
    data = _config(root, WRONG_INDEX, report="html")
    assert cli.main(["-c", str(write_config(root, data)), "check"]) == 1
    out = capsys.readouterr().out
    assert "'sw_tracing_report'" not in out
    assert "'sw_architecture' is no page" in out

    # Placeholders, explicit page names, the subpages of the tracing report and a Markdown
    # document with its own toctree list every document.
    (root / "docs" / "notes.md").write_text(NOTES_MD, encoding="utf-8")
    data = _config(root, GOOD_INDEX)
    data["documents"].append({"id": "notes", "type": "markdown", "source": "docs/notes.md"})
    (root / "docs" / "index.rst").write_text(GOOD_INDEX.replace("/sw_test/index.rst", "notes.md"), encoding="utf-8")
    assert cli.main(["-c", str(write_config(root, data)), "check"]) == 0
    assert "Table of contents" not in capsys.readouterr().out

    # Without project start page, trlcdoc generates the table of contents, there is nothing to check.
    data = base_config()
    assert cli.main(["-c", str(write_config(root, data)), "check"]) == 0

    # A placeholder naming no document is a configuration error, exit code 2.
    data = _config(root, WRONG_INDEX.replace("{page:sw_requirements}", "{page:sw_req}\n   {page:sw-arch}"))
    assert cli.main(["-c", str(write_config(root, data)), "check"]) == 2
    out = capsys.readouterr().out
    assert "html.index: placeholder '{page:sw_req}' names no document." in out
    assert "html.index: placeholder '{page:sw-arch}' names no document." in out


def test_toctree_entries() -> None:
    """Toctree entries are read from reStructuredText and MyST Markdown pages as page names."""

    rst = """.. toctree::
   :maxdepth: 2

   page_a
   Title <folder/page_b>
   /page_c.rst
   ./page_d.md
   self
   https://example.com
   chapter*

Text after the toctree, not indented.

   .. toctree::

      nested
"""
    assert toctree_entries(rst) == ["page_a", "folder/page_b", "page_c", "page_d", "nested"]
    assert toctree_entries(rst.replace("\n", "\r\n")) == ["page_a", "folder/page_b", "page_c", "page_d", "nested"]

    markdown = """# Title

````{toctree}
:maxdepth: 1
page_a
````

:::{toctree}
---
caption: Contents
---
Title <page_b>
:::

```python
not_a_page
```
"""
    assert toctree_entries(markdown, markdown=True) == ["page_a", "page_b"]


def test_page_placeholders(project: Path) -> None:
    """The page placeholders are replaced by the page names relative to the page using them.

    Args:
        project (Path): Configuration file of the example project.
    """
    root = project.parent
    data = _config(root, "")
    data["documents"].append({"id": "guide", "type": "rst", "source": "docs/index.rst"})
    cfg = load_config(write_config(root, data))
    text = "{page:sw_requirements} {page:sw_tracing_report} {page:guide} {page:unknown} {project_root}\n" \
           "   {documents}\r\n"

    # {documents} keeps the indentation and the CRLF line end of its line for every page.
    top = replace_placeholders(cfg, text, cfg.sphinx_dir / "index.rst").split("\n")
    assert top[0] == "sw_requirements/index sw_tracing_report/index guide {page:unknown} ../../.."
    assert top[1:] == [f"   {page}\r" for page in ("sw_requirements/index", "sw_architecture/index", "sw_test/index",
                                                    "sw_test_results/index", "sw_tracing_report/index", "guide")] + [""]

    # In a page of a document folder, e.g. with the page header, the names are relative to the folder.
    nested = replace_placeholders(cfg, text, cfg.sphinx_dir / "sw_test" / "index.rst").split("\n")
    assert nested[0] == "../sw_requirements/index ../sw_tracing_report/index ../guide {page:unknown} ../../../.."

    # With the HTML tracing report, the tracing report is a single page.
    data["trace"]["report"] = "html"
    cfg = load_config(write_config(root, data))
    assert replace_placeholders(cfg, "{page:sw_tracing_report}", cfg.sphinx_dir / "index.rst") == "sw_tracing_report"

