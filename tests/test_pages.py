# Start page listing the tracing report by its name for trace.report: html, an unknown page,
# a TRLC document without /index and a page generated by a Sphinx extension.
WRONG_INDEX = """Example
=======

.. toctree::
   :maxdepth: 1
   :caption: Contents:

   {page:sw_requirements}
   sw_architecture
   Tracing <sw_tracing_report>
   sw_tests_old
   api/example/index
"""

# Start page with every document, by placeholder and by explicit page name.
GOOD_INDEX = """Example
=======

.. toctree::
   :caption: Contents:

   {page:sw_requirements}
   sw_architecture/index
   /sw_test/index.rst
   self

.. toctree::
   :caption: Reports:

   {page:sw_test_results}
   sw_tracing_report/index
   sw_tracing_report/sw_requirement
   https://example.com
"""

# Markdown page with a MyST toctree, listing a document instead of the start page.
NOTES_MD = """# Notes

```{toctree}
---
maxdepth: 1
---
{page:sw_test}
```
"""

